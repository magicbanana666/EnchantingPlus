"""Closed beveled stone and faceted crystals for NeoForge's OBJ loader."""
import json
import math


def sub(a,b): return [x-y for x,y in zip(a,b)]
def cross(a,b): return [a[1]*b[2]-a[2]*b[1],a[2]*b[0]-a[0]*b[2],a[0]*b[1]-a[1]*b[0]]
def dot(a,b): return sum(x*y for x,y in zip(a,b))


def export_table(assets, elements, textures):
    faces=[]

    def face(name, points, tex, normal, uv=None, emission=0):
        uv=uv or ([[0,0],[16,0],[16,16]] if len(points)==3 else [[0,0],[16,0],[16,16],[0,16]])
        points=[list(p) for p in points]
        n=cross(sub(points[1],points[0]),sub(points[2],points[0]))
        if dot(n,normal)<0:
            points.reverse();uv=list(reversed(uv));n=[-v for v in n]
        length=math.sqrt(dot(n,n))
        assert length>1e-8, name
        assert all(0<=v<=16 for p in points for v in p), name
        faces.append({'name':name,'points':points,'uv':uv,'texture':tex,'normal':[v/length for v in n],'emission':emission})

    for e in elements:
        x,y,z=e['from']; X,Y,Z=e['to']
        sides={
            'up':([[x,Y,z],[X,Y,z],[X,Y,Z],[x,Y,Z]],[0,1,0]),
            'down':([[x,y,Z],[X,y,Z],[X,y,z],[x,y,z]],[0,-1,0]),
            'south':([[x,Y,Z],[X,Y,Z],[X,y,Z],[x,y,Z]],[0,0,1]),
            'north':([[X,Y,z],[x,Y,z],[x,y,z],[X,y,z]],[0,0,-1]),
            'east':([[X,Y,Z],[X,Y,z],[X,y,z],[X,y,Z]],[1,0,0]),
            'west':([[x,Y,z],[x,Y,Z],[x,y,Z],[x,y,z]],[-1,0,0]),
        }
        for side,(points,n) in sides.items():
            if 'rotation' in e:
                r=e['rotation'];a=math.radians(r['angle']);c,s=math.cos(a),math.sin(a)
                def rotate(p):
                    x,y,z=p
                    if r['axis']=='x': return [x,c*y-s*z,s*y+c*z]
                    if r['axis']=='z': return [c*x-s*y,s*x+c*y,z]
                    return [c*x+s*z,y,-s*x+c*z]
                points=[[v+o for v,o in zip(rotate(sub(p,r['origin'])),r['origin'])] for p in points]
                n=rotate(n)
            f=e['faces'][side];u,v,U,V=f['uv']
            face(e['name'],points,f['texture'][1:],n,[[u,v],[U,v],[U,V],[u,V]],e.get('light_emission',0))

    # The original stepped masonry crown is exported from the boxes above.
    # Keep the newer faceted crystals independently of that restored tabletop.
    for cx in (2.2,13.8):
        for cz in (2.2,13.8):
            name=f'Crystal {cx} {cz}'
            rings=[]
            for y,r in ((12.25,.72),(12.72,.9),(13.2,.57)):
                rings.append([[cx+r*math.cos(math.pi/8+i*math.pi/4),y,cz+r*math.sin(math.pi/8+i*math.pi/4)] for i in range(8)])
            for i in range(8):
                j=(i+1)%8
                mid=(i+.5)*math.pi/4+math.pi/8
                n=[math.cos(mid),.2,math.sin(mid)]
                face(name,[[cx,12.25,cz],rings[0][i],rings[0][j]],'crystal',[0,-1,0],emission=8)
                for a,b in zip(rings,rings[1:]):
                    face(name,[a[i],a[j],b[j],b[i]],'crystal',n,emission=8)
                face(name,[rings[-1][i],rings[-1][j],[cx,13.7,cz]],'crystal',n,[[0,16],[16,16],[8,0]],8)

    model_dir=assets/'models/block'
    lines=['# Generated by tools/build_table_assets.py','mtllib advanced_table.mtl']
    index=1
    for face_index,f in enumerate(faces):
        tint=1.0
        if f['texture']=='crystal':
            tint=round(.65+.35*max(0,dot(f['normal'],[-.3,.85,.43])),2)
        f['tint']=tint
        material=f['texture']+('_lit' if f['emission'] else '')+('_'+str(round(tint*100)) if tint!=1 else '')
        f['material']=material
        # ObjGeometry replaces groups with duplicate names. Give each face a
        # unique group so all six sides survive loading, including undersides.
        lines.extend(['g '+f['name'].replace(' ','_')+'_'+str(face_index),'usemtl '+material])
        for p in f['points']: lines.append('v '+' '.join(f'{v/16:.8f}' for v in p))
        for u,v in f['uv']: lines.append(f'vt {u/16:.8f} {1-v/16:.8f}')
        for p in f['points']: lines.append('vn '+' '.join(f'{v:.8f}' for v in f['normal']))
        lines.append('f '+' '.join(f'{i}/{i}/{i}' for i in range(index,index+len(f['points']))))
        index+=len(f['points'])
    (model_dir/'advanced_table.obj').write_text('\n'.join(lines)+'\n')
    materials={f['material']:(f['texture'],f['emission'],f['tint']) for f in faces}
    mtl=[]
    for name,(texture,emission,tint) in materials.items():
        mtl.extend(['newmtl '+name,f'Kd {tint} {tint} {tint}',f'Ka {emission/15:.6f} {emission/15:.6f} {emission/15:.6f}','map_Kd #'+texture,''])
    (model_dir/'advanced_table.mtl').write_text('\n'.join(mtl))
    model={'parent':'minecraft:block/block','loader':'neoforge:obj','model':'eplusplus:models/block/advanced_table.obj','automatic_culling':False,'shade_quads':True,'flip_v':True,'emissive_ambient':True,'ambientocclusion':True,'textures':textures}
    (model_dir/'advanced_table.json').write_text(json.dumps(model,indent=2)+'\n')
    return faces
